"""
RAGAS Evaluation Routes

Provides endpoints for RAG evaluation using RAGAS metrics:
- Faithfulness: Measures if the answer is grounded in the given context
- Answer Relevancy: Measures how relevant the answer is to the question
- Context Precision: Measures the precision of the retrieved context
- Context Recall: Measures the recall of the retrieved context
"""

import logging
import os
from typing import List, Optional, Dict, Any
from fastapi import APIRouter, HTTPException
from pydantic import BaseModel, Field
import requests
import httpx

logger = logging.getLogger(__name__)

# RAGAS Service URL
RAGAS_SERVICE_URL = os.getenv(
    'RAGAS_SERVICE_URL',
    os.getenv('RAGAS_SERVICE_HOST', 'http://ragas-service:8010')
)
# Ensure we have the full URL
if not RAGAS_SERVICE_URL.startswith('http'):
    RAGAS_SERVICE_PORT = os.getenv('RAGAS_SERVICE_PORT', '8010')
    RAGAS_SERVICE_URL = f'http://{RAGAS_SERVICE_URL}:{RAGAS_SERVICE_PORT}'

router = APIRouter(prefix="/rag-metrics", tags=["RAG Metrics (RAGAS)"])


class RAGASEvaluationRequest(BaseModel):
    """Request model for RAGAS evaluation"""
    question: str = Field(..., description="The question being asked")
    answer: str = Field(..., description="The answer generated by the RAG system")
    contexts: List[str] = Field(..., description="List of context documents used to generate the answer")
    ground_truth: Optional[str] = Field(None, description="Optional ground truth answer for context precision/recall")


class RAGASEvaluationResponse(BaseModel):
    """Response model for RAGAS evaluation"""
    faithfulness: float = Field(..., description="Faithfulness score (0-1)")
    answer_relevancy: float = Field(..., description="Answer relevancy score (0-1)")
    context_precision: Optional[float] = Field(None, description="Context precision score (0-1), requires ground_truth")
    context_recall: Optional[float] = Field(None, description="Context recall score (0-1), requires ground_truth")
    overall_score: float = Field(..., description="Overall average score")
    metrics_available: List[str] = Field(..., description="List of metrics that were calculated")


@router.get("/health")
async def health_check():
    """Health check endpoint"""
    try:
        # Check if RAGAS service is available
        async with httpx.AsyncClient(timeout=5.0) as client:
            response = await client.get(f"{RAGAS_SERVICE_URL}/health")
            if response.status_code == 200:
                return {
                    "status": "healthy",
                    "ragas_service": "available",
                    "ragas_service_url": RAGAS_SERVICE_URL
                }
            else:
                return {
                    "status": "degraded",
                    "ragas_service": "unavailable",
                    "ragas_service_url": RAGAS_SERVICE_URL,
                    "error": f"RAGAS service returned status {response.status_code}"
                }
    except Exception as e:
        logger.error(f"Health check failed: {e}")
        return {
            "status": "unhealthy",
            "ragas_service": "unavailable",
            "ragas_service_url": RAGAS_SERVICE_URL,
            "error": str(e)
        }


@router.post("/evaluate", response_model=RAGASEvaluationResponse)
async def evaluate_rag(request: RAGASEvaluationRequest):
    """
    Evaluate RAG performance using RAGAS metrics
    
    This endpoint forwards the evaluation request to the RAGAS service
    and returns the calculated metrics.
    """
    try:
        logger.info(f"Evaluating RAG performance for question: {request.question[:50]}...")
        
        # Forward request to RAGAS service
        async with httpx.AsyncClient(timeout=60.0) as client:
            response = await client.post(
                f"{RAGAS_SERVICE_URL}/evaluate",
                json={
                    "question": request.question,
                    "answer": request.answer,
                    "contexts": request.contexts,
                    "ground_truth": request.ground_truth
                }
            )
            
            if response.status_code != 200:
                error_text = await response.aread()
                logger.error(f"RAGAS service error: {response.status_code} - {error_text.decode()}")
                raise HTTPException(
                    status_code=response.status_code,
                    detail=f"RAGAS service error: {error_text.decode()}"
                )
            
            result = response.json()
            
            # Determine which metrics were calculated
            metrics_available = ["faithfulness", "answer_relevancy"]
            if request.ground_truth:
                metrics_available.extend(["context_precision", "context_recall"])
            
            return RAGASEvaluationResponse(
                faithfulness=result.get("faithfulness", 0.0),
                answer_relevancy=result.get("answer_relevancy", 0.0),
                context_precision=result.get("context_precision"),
                context_recall=result.get("context_recall"),
                overall_score=result.get("overall_score", 0.0),
                metrics_available=metrics_available
            )
            
    except httpx.TimeoutException:
        logger.error("RAGAS service timeout")
        raise HTTPException(
            status_code=504,
            detail="RAGAS service request timed out. The evaluation may take longer than expected."
        )
    except httpx.ConnectError:
        logger.error(f"Could not connect to RAGAS service at {RAGAS_SERVICE_URL}")
        raise HTTPException(
            status_code=503,
            detail=f"RAGAS service is unavailable at {RAGAS_SERVICE_URL}. Please check if the service is running."
        )
    except Exception as e:
        logger.error(f"Evaluation error: {e}", exc_info=True)
        raise HTTPException(
            status_code=500,
            detail=f"Evaluation failed: {str(e)}"
        )


@router.post("/evaluate-batch")
async def evaluate_rag_batch(requests: List[RAGASEvaluationRequest]):
    """
    Evaluate multiple RAG queries in batch
    
    This endpoint evaluates multiple question-answer pairs and returns
    aggregated metrics.
    """
    try:
        logger.info(f"Evaluating batch of {len(requests)} RAG queries")
        
        results = []
        for i, req in enumerate(requests):
            try:
                # Use the single evaluation endpoint
                result = await evaluate_rag(req)
                results.append({
                    "index": i,
                    "question": req.question,
                    "result": result.dict(),
                    "success": True
                })
            except Exception as e:
                logger.error(f"Failed to evaluate query {i}: {e}")
                results.append({
                    "index": i,
                    "question": req.question,
                    "error": str(e),
                    "success": False
                })
        
        # Calculate aggregate metrics
        successful_results = [r for r in results if r.get("success")]
        if successful_results:
            avg_faithfulness = sum(r["result"]["faithfulness"] for r in successful_results) / len(successful_results)
            avg_answer_relevancy = sum(r["result"]["answer_relevancy"] for r in successful_results) / len(successful_results)
            avg_overall = sum(r["result"]["overall_score"] for r in successful_results) / len(successful_results)
            
            # Calculate context metrics if available
            context_results = [r for r in successful_results if r["result"].get("context_precision") is not None]
            avg_context_precision = None
            avg_context_recall = None
            if context_results:
                avg_context_precision = sum(r["result"]["context_precision"] for r in context_results) / len(context_results)
                avg_context_recall = sum(r["result"]["context_recall"] for r in context_results) / len(context_results)
            
            return {
                "total_queries": len(requests),
                "successful": len(successful_results),
                "failed": len(requests) - len(successful_results),
                "aggregate_metrics": {
                    "average_faithfulness": avg_faithfulness,
                    "average_answer_relevancy": avg_answer_relevancy,
                    "average_context_precision": avg_context_precision,
                    "average_context_recall": avg_context_recall,
                    "average_overall_score": avg_overall
                },
                "results": results
            }
        else:
            return {
                "total_queries": len(requests),
                "successful": 0,
                "failed": len(requests),
                "error": "All evaluations failed",
                "results": results
            }
            
    except Exception as e:
        logger.error(f"Batch evaluation error: {e}", exc_info=True)
        raise HTTPException(
            status_code=500,
            detail=f"Batch evaluation failed: {str(e)}"
        )

