# Database for RAGAS test persistence
RAGAS_TEST_DB_PATH = Path("data/ragas_test_results.db")

def _init_ragas_test_db():
    """Initialize RAGAS test results database"""
    RAGAS_TEST_DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    with sqlite3.connect(RAGAS_TEST_DB_PATH) as conn:
        conn.execute("""
            CREATE TABLE IF NOT EXISTS ragas_test_results (
                test_id TEXT PRIMARY KEY,
                data TEXT NOT NULL,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        """)

def _save_ragas_test_to_db(test_id: str, test_data: Dict[str, Any]):
    """Save RAGAS test data to database and update memory"""
    try:
        with sqlite3.connect(RAGAS_TEST_DB_PATH) as conn:
            conn.execute("""
                INSERT OR REPLACE INTO ragas_test_results (test_id, data, updated_at)
                VALUES (?, ?, CURRENT_TIMESTAMP)
            """, (test_id, json.dumps(test_data, default=str, ensure_ascii=False)))
        
        # CRITICAL: Always update memory after saving to DB to prevent cache issues
        # This ensures memory and DB stay in sync
        RAGAS_TEST_STORAGE[test_id] = test_data.copy()  # Use copy to avoid reference issues
        logger.debug(f"💾 Saved test {test_id} to DB and updated memory")
    except Exception as e:
        logger.warning(f"Failed to save RAGAS test to DB: {e}")

def _load_ragas_test_from_db(test_id: str) -> Optional[Dict[str, Any]]:
    """Load RAGAS test data from database"""
    try:
        with sqlite3.connect(RAGAS_TEST_DB_PATH) as conn:
            cursor = conn.execute("SELECT data FROM ragas_test_results WHERE test_id = ?", (test_id,))
            row = cursor.fetchone()
            if row:
                return json.loads(row[0])
    except Exception as e:
        logger.warning(f"Failed to load RAGAS test from DB: {e}")
    return None

# Initialize database on startup
_init_ragas_test_db()


class RAGASEvaluationRequest(BaseModel):
    """Request model for RAGAS evaluation"""
    question: str = Field(..., description="The question being asked")
    answer: str = Field(..., description="The answer generated by the RAG system")
    contexts: List[str] = Field(..., description="List of context passages used")
    ground_truth: Optional[str] = Field(None, description="Optional ground truth answer for evaluation")
    llm_provider: Optional[str] = Field(None, description="Optional LLM provider override for RAGAS evaluation (e.g., groq, openai, openrouter)")
    llm_model: Optional[str] = Field(None, description="Optional LLM model override for RAGAS evaluation")


class RAGASEvaluationResponse(BaseModel):
    """Response model for RAGAS evaluation"""
    faithfulness: float = Field(..., description="Faithfulness score (0-1)")
    answer_relevancy: float = Field(..., description="Answer relevancy score (0-1)")
    answer_correctness: Optional[float] = Field(None, description="Answer correctness score (0-1), requires ground_truth")
    context_precision: Optional[float] = Field(None, description="Context precision score (0-1), requires ground_truth")
    context_recall: Optional[float] = Field(None, description="Context recall score (0-1), requires ground_truth")
    overall_score: float = Field(..., description="Overall average score")
    metrics_available: List[str] = Field(..., description="List of metrics that were calculated")


# Batch Evaluation Models (similar to test-simulation)
