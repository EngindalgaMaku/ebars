@router.post("/evaluate-batch")
async def evaluate_rag_batch(requests: List[RAGASEvaluationRequest]):
    """
    Evaluate multiple RAG queries in batch
    
    This endpoint evaluates multiple question-answer pairs and returns
    aggregated metrics.
    """
    try:
        logger.info(f"Evaluating batch of {len(requests)} RAG queries")
        
        results = []
        for i, req in enumerate(requests):
            try:
                # Use the single evaluation endpoint
                result = await evaluate_rag(req)
                results.append({
                    "index": i,
                    "question": req.question,
                    "result": result.dict(),
                    "success": True
                })
            except Exception as e:
                logger.error(f"Failed to evaluate query {i}: {e}")
                results.append({
                    "index": i,
                    "question": req.question,
                    "error": str(e),
                    "success": False
                })
        
        # Calculate aggregate metrics
        successful_results = [r for r in results if r.get("success")]
        if successful_results:
            avg_faithfulness = sum(r["result"]["faithfulness"] for r in successful_results) / len(successful_results)
            avg_answer_relevancy = sum(r["result"]["answer_relevancy"] for r in successful_results) / len(successful_results)
            avg_overall = sum(r["result"]["overall_score"] for r in successful_results) / len(successful_results)
            
            # Calculate context metrics if available
            context_results = [r for r in successful_results if r["result"].get("context_precision") is not None]
            avg_context_precision = None
            avg_context_recall = None
            if context_results:
                avg_context_precision = sum(r["result"]["context_precision"] for r in context_results) / len(context_results)
                avg_context_recall = sum(r["result"]["context_recall"] for r in context_results) / len(context_results)
            
            return {
                "total_queries": len(requests),
                "successful": len(successful_results),
                "failed": len(requests) - len(successful_results),
                "aggregate_metrics": {
                    "average_faithfulness": avg_faithfulness,
                    "average_answer_relevancy": avg_answer_relevancy,
                    "average_context_precision": avg_context_precision,
                    "average_context_recall": avg_context_recall,
                    "average_overall_score": avg_overall
                },
                "results": results
            }
        else:
            return {
                "total_queries": len(requests),
                "successful": 0,
                "failed": len(requests),
                "error": "All evaluations failed",
                "results": results
            }
            
    except Exception as e:
        logger.error(f"Batch evaluation error: {e}", exc_info=True)
        raise HTTPException(
            status_code=500,
            detail=f"Batch evaluation failed: {str(e)}"
        )

